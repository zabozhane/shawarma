export function detectLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && T[saved]) return saved;
  } catch { /* браузер без хранилища */ }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || 'ru'];
  for (const p of prefs) {
    const code = String(p).slice(0, 2).toLowerCase();
    if (T[code]) return code;
  }
  return 'ru';
}

export function makeT(lang) {
  const dict = T[lang] || T.ru;
  return (key, vars = {}) =>
    (dict[key] ?? T.ru[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

